func TestPostgresOptionsValidation(t *testing.T) {
	valid := PostgresOptions{URL: "postgres://arrmada:secret@localhost/arrmada?sslmode=verify-full", Schema: "arrmada"}
	if err := valid.validate(); err != nil {
		t.Fatal(err)
	}
	for _, schema := range []string{"", "public", "information_schema", "pg_catalog", "pg_temp", "pg_other", "a,b", "MixedCase", "a.b", `a"`, "a;DROP TABLE users", strings.Repeat("a", 64)} {
		t.Run("schema/"+schema, func(t *testing.T) {
			opt := valid
			opt.Schema = schema
			if err := opt.validate(); err == nil {
				t.Fatalf("accepted schema %q", schema)
			}
		})
	}
	for _, schema := range []string{"arrmada", "arrmada_2", "_arrmada", strings.Repeat("a", 63)} {
		opt := valid
		opt.Schema = schema
		if err := opt.validate(); err != nil {
			t.Errorf("rejected schema %q: %v", schema, err)
		}
	}
	for _, address := range []string{"", "host=localhost password=secret", "sqlite://localhost/data", "postgres://localhost/arrmada", "postgres://arrmada@/arrmada", "postgres://arrmada@localhost/", "postgres://arrmada:secret@localhost/arrmada#fragment", "postgres://arrmada:secret%xx@localhost/arrmada"} {
		opt := valid
		opt.URL = address
		if err := opt.validate(); err == nil {
			t.Errorf("accepted incomplete URL %q", address)
		} else if strings.Contains(err.Error(), "secret") {
			t.Errorf("validation exposed credentials: %v", err)
		}
	}
	valid.MaxConnections = -1
	if err := valid.validate(); err == nil {
		t.Fatal("accepted negative pool size")
	}
}

func TestPostgresParseErrorDoesNotExposeCredentials(t *testing.T) {
	_, err := openPostgresPool(context.Background(), PostgresOptions{
		URL: "postgres://arrmada:do-not-log-me@localhost/arrmada?sslmode=invalid", Schema: "arrmada",
	})
	if err == nil || strings.Contains(err.Error(), "do-not-log-me") {
		t.Fatalf("expected a sanitized configuration error, got %v", err)
	}
}

// postgresFixture requires an explicitly supplied disposable database. Only
// the test setup uses its administrator; the pool under test logs in as a new
// NOSUPERUSER NOCREATEDB NOCREATEROLE role that owns one dedicated schema.
func postgresFixture(t *testing.T) (context.Context, *pgx.Conn, PostgresOptions, string) {
	t.Helper()
	address := os.Getenv("ARRMADA_TEST_POSTGRES_ADMIN_URL")
	if address == "" {
		t.Skip("set ARRMADA_TEST_POSTGRES_ADMIN_URL to an administrator URL for a disposable PostgreSQL database")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	t.Cleanup(cancel)
	admin, err := pgx.Connect(ctx, address)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = admin.Close(context.Background()) })
	name := fmt.Sprintf("arrmada_test_%x", rand.Text()[:12])
	password := rand.Text()
	other := name + "_other"
	quoted := pgx.Identifier{name}.Sanitize()
	quotedOther := pgx.Identifier{other}.Sanitize()
	var createRole string
	if err := admin.QueryRow(ctx, `SELECT format('CREATE ROLE %I LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT PASSWORD %L', $1::text, $2::text)`, name, password).Scan(&createRole); err != nil {
		t.Fatal(err)
	}
	if _, err := admin.Exec(ctx, createRole); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		cleanupCtx, cleanupCancel := context.WithTimeout(context.Background(), 10*time.Second)
		defer cleanupCancel()
		// Names are generated by this fixture, never supplied by the environment.
		for _, statement := range []string{"DROP SCHEMA IF EXISTS " + quoted + " CASCADE", "DROP SCHEMA IF EXISTS " + quotedOther + " CASCADE", "DROP ROLE " + quoted} {
			if _, err := admin.Exec(cleanupCtx, statement); err != nil {
				t.Errorf("clean up PostgreSQL fixture: %v", err)
			}
		}
	})
	for _, statement := range []string{
		"CREATE SCHEMA " + quoted + " AUTHORIZATION " + quoted,
		"CREATE SCHEMA " + quotedOther,
		"CREATE TABLE " + quotedOther + ".sentinel (value text NOT NULL)",
		"INSERT INTO " + quotedOther + ".sentinel VALUES ('unrelated application')",
	} {
		if _, err := admin.Exec(ctx, statement); err != nil {
			t.Fatal(err)
		}
	}
	u, err := url.Parse(address)
	if err != nil {
		t.Fatal("test administrator connection must be a URL")
	}
	u.User = url.UserPassword(name, password)
	q := u.Query()
	q.Del("user")
	q.Del("password")
	// URL/session overrides must not let repository queries escape the
	// designated schema, even when that schema contains the same table names.
	q.Set("search_path", other+",public")
	q.Set("timezone", "Pacific/Honolulu")
	q.Set("standard_conforming_strings", "off")
	q.Set("default_transaction_isolation", "serializable")
	q.Set("datestyle", "SQL, DMY")
	q.Set("client_encoding", "LATIN1")
	q.Set("options", "-csearch_path="+other+",public -ctimezone=Pacific/Honolulu -cstandard_conforming_strings=off -cdefault_transaction_isolation=serializable -cDateStyle=SQL,DMY")
	u.RawQuery = q.Encode()
	return ctx, admin, PostgresOptions{URL: u.String(), Schema: name, MaxConnections: 2}, other
}

func TestPostgresPoolRestrictedRoleAndSchema(t *testing.T) {
	ctx, admin, opt, other := postgresFixture(t)
	db, err := openPostgresPool(ctx, opt)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = db.Close() })
	if db.Dialect() != Postgres {
		t.Fatal("wrong dialect")
	}
	if _, err := db.ExecContext(ctx, `CREATE TABLE sentinel (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, value text NOT NULL)`); err != nil {
		t.Fatal(err)
	}
	var id int64
	if err := db.QueryRowContext(ctx, `INSERT INTO sentinel (value) VALUES (?) RETURNING id`, "Arrmada's ? data").Scan(&id); err != nil || id != 1 {
		t.Fatalf("insert = %d, %v", id, err)
	}
	if _, err := db.ExecContext(ctx, `INSERT INTO sentinel (id, value) VALUES (?, ?)`, id, "duplicate"); !IsUniqueViolation(err) {
		t.Fatalf("primary-key violation not classified: %v", err)
	}
	if _, err := db.ExecContext(ctx, `INSERT INTO sentinel (value) VALUES (NULL)`); err == nil || IsUniqueViolation(err) {
		t.Fatalf("not-null failure incorrectly classified: %v", err)
	}
	stmt, err := db.PrepareContext(ctx, `SELECT value FROM sentinel WHERE id = ?`)
	if err != nil {
		t.Fatal(err)
	}
	defer stmt.Close()
	var value string
	if err := stmt.QueryRowContext(ctx, id).Scan(&value); err != nil || value != "Arrmada's ? data" {
		t.Fatalf("prepared query = %q, %v", value, err)
	}
	var jsonKey bool
	if err := db.QueryRowContext(ctx, `SELECT '{"key":1}'::jsonb ?? ?`, "key").Scan(&jsonKey); err != nil || !jsonKey {
		t.Fatalf("question-mark operator = %v, %v", jsonKey, err)
	}
	// Hold both pool connections at once: the second must not inherit the
	// shared server's search_path or timezone instead of the configured ones.
	for range 2 {
		conn, err := db.pool.Conn(ctx)
		if err != nil {
			t.Fatal(err)
		}
		defer conn.Close()
		var schema, zone, conforming, isolation, dateStyle, encoding string
		if err := conn.QueryRowContext(ctx, `SELECT current_schema(), current_setting('TimeZone'), current_setting('standard_conforming_strings'), current_setting('transaction_isolation'), current_setting('DateStyle'), current_setting('client_encoding')`).Scan(&schema, &zone, &conforming, &isolation, &dateStyle, &encoding); err != nil || schema != opt.Schema || zone != "UTC" || conforming != "on" || isolation != "read committed" || dateStyle != "ISO, YMD" || encoding != "UTF8" {
			t.Fatalf("session = %q, %q, %q, %q, %q, %q, %v", schema, zone, conforming, isolation, dateStyle, encoding, err)
		}
		var superuser, createdb, createrole bool
		if err := conn.QueryRowContext(ctx, `SELECT rolsuper, rolcreatedb, rolcreaterole FROM pg_catalog.pg_roles WHERE rolname = current_user`).Scan(&superuser, &createdb, &createrole); err != nil || superuser || createdb || createrole {
			t.Fatalf("unexpected administrative privileges: %v, %v, %v, %v", superuser, createdb, createrole, err)
		}
	}
	if err := admin.QueryRow(ctx, "SELECT value FROM "+pgx.Identifier{other, "sentinel"}.Sanitize()).Scan(&value); err != nil || value != "unrelated application" {
		t.Fatalf("unrelated data changed: %q, %v", value, err)
	}
}

func TestPostgresPoolRefusesMissingOrUnownedSchema(t *testing.T) {
	ctx, admin, opt, other := postgresFixture(t)
	for _, schema := range []string{opt.Schema + "_missing", other} {
		candidate := opt
		candidate.Schema = schema
		if db, err := openPostgresPool(ctx, candidate); err == nil {
			_ = db.Close()
			t.Fatalf("opened missing or unowned schema %q", schema)
		}
	}
	var exists bool
	if err := admin.QueryRow(ctx, `SELECT EXISTS (SELECT 1 FROM pg_catalog.pg_namespace WHERE nspname = $1)`, opt.Schema+"_missing").Scan(&exists); err != nil || exists {
		t.Fatalf("connector created a schema: %v, %v", exists, err)
	}
}

func TestPostgresTransactionBindingAndRollback(t *testing.T) {
	ctx, _, opt, _ := postgresFixture(t)
	db, err := openPostgresPool(ctx, opt)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = db.Close() })
	if _, err := db.ExecContext(ctx, `CREATE TABLE changes (value text NOT NULL)`); err != nil {
		t.Fatal(err)
	}
	native, err := db.pool.BeginTx(ctx, nil)
	if err != nil {
		t.Fatal(err)
	}
	defer native.Rollback()
	tx := &Transaction{tx: native, dialect: db.Dialect()}
	if _, err := tx.ExecContext(ctx, `INSERT INTO changes (value) VALUES (?)`, "uncommitted"); err != nil {
		t.Fatal(err)
	}
	var value string
	if err := tx.QueryRowContext(ctx, `SELECT value FROM changes WHERE value = ?`, "uncommitted").Scan(&value); err != nil || value != "uncommitted" {
		t.Fatalf("transaction query = %q, %v", value, err)
	}
	if err := native.Rollback(); err != nil {
		t.Fatal(err)
	}
	var count int
	if err := db.QueryRowContext(ctx, `SELECT COUNT(*) FROM changes`).Scan(&count); err != nil || count != 0 {
		t.Fatalf("rolled-back data present: %d, %v", count, err)
	}
}
